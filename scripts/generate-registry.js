const files = fs.readdirSync(uiDir).filter(f => f.endsWith('.tsx') || f.endsWith('.ts'));

const entries = [];

files.forEach(file => {
  const filePath = path.join(uiDir, file);
  const content = fs.readFileSync(filePath, 'utf8');
  
  const baseName = file.replace(/\.(tsx|ts)$/, '');
  const lowerBase = baseName.toLowerCase();
  
  // Format component name (e.g. autocomplete -> Autocomplete, AppModal -> AppModal)
  let componentName = baseName;
  if (baseName.charAt(0) === baseName.charAt(0).toLowerCase()) {
    componentName = baseName.charAt(0).toUpperCase() + baseName.slice(1).replace(/-([a-z])/g, g => g[1].toUpperCase());
  }
  
  // Map category
  const category = CATEGORY_MAP[lowerBase] || CATEGORY_MAP[lowerBase.replace('-card', '')] || CATEGORY_MAP[lowerBase.replace('-input', '')] || "Utilities";
  
  // Don't register helpers like OutlineDraw or source code files that are not react components
  if (baseName === 'OutlineDraw') return;
  
  entries.push({
    name: componentName,
    fileName: baseName,
    category,
    source: content
  });
});

let registryContent = `// This file is auto-generated by scripts/generate-registry.js. Do not edit directly.
import React from 'react';
import dynamic from 'next/dynamic';

export interface ComponentMeta {
  name: string;
  category: string;
  component: React.ComponentType<any>;
  source: string;
}

export const componentsRegistry: ComponentMeta[] = [
`;

entries.forEach(entry => {
  const escapedSource = JSON.stringify(entry.source);
  registryContent += `  {
    name: "${entry.name}",
    category: "${entry.category}",
    component: React.lazy(() => import('@/app/components/ui/${entry.fileName}')),
    source: ${escapedSource}
  },\n`;
});

registryContent += `];\n`;

fs.writeFileSync(outputFile, registryContent, 'utf8');
console.log(`Registry generated with ${entries.length} components.`);
