// Builds lib/catalog-index.ts and public/catalog-src/* from components/catalog/*Family.tsx and TabBatch*.tsx.
// Every `export function Name()` in those files is one designed component.
const fs = require('fs');
const { buildIndex, standalone } = require('./standalone');
const path = require('path');
const dir = path.join(__dirname, '../components/catalog');
const FAMILIES = [
  ['ButtonFamily', 'Buttons'], ['BadgesFamily', 'Badges & Avatars'], ['CardFamily', 'Cards'], ['ChartFamily', 'Charts'],
  ['DataDisplayFamily', 'Data display'], ['FormsFamily', 'Forms'], ['InputFamily', 'Inputs'], ['MenuFamily', 'Menus'],
  ['ModalFamily', 'Modals'], ['NavFlowFamily', 'Navigation flows'], ['NavbarFamily', 'Navbars'], ['SectionsFamily', 'Sections'],
  ['SliderFamily', 'Sliders'], ['TableFamily', 'Tables'], ['ToastFamily', 'Toasts'], ['LoadersFamily', 'Loaders'],
  ['AccordionFamily', 'Accordions'], ['TabBatchA', 'Tabs'], ['TabBatchB', 'Tabs'], ['TabBatchC', 'Tabs'], ['TabBatchD', 'Tabs'],
];
const outSrc = path.join(__dirname, '../public/catalog-src');
fs.mkdirSync(outSrc, { recursive: true });
const items = [];
for (const [file, category] of FAMILIES) {
  const p = path.join(dir, file + '.tsx');
  if (!fs.existsSync(p)) continue;
  const src = fs.readFileSync(p, 'utf8');
  const re = /^export function ([A-Z][A-Za-z0-9]*)\(/gm;
  const found = [];
  let m;
  while ((m = re.exec(src))) found.push({ name: m[1], start: m.index });
  const code = {};
  const sa = {};
  const index = buildIndex(src);
  const cssName = fs.existsSync(path.join(dir, file + '.css')) ? file + '.css' : null;
  found.forEach((f, i) => {
    const rest = src.slice(f.start);
    const end = rest.search(/\n}\n/);
    code[f.name] = end >= 0 ? rest.slice(0, end + 3) : rest;
    const r = standalone(index, f.name, cssName, dir, (d, rel) => { const fp = path.join(d, rel.replace(/\.tsx?$/, '') + '.tsx'); return fs.existsSync(fp) ? buildIndex(fs.readFileSync(fp, 'utf8')) : null; });
    if (r) sa[f.name] = r;
    items.push({ id: `${file}.${f.name}`, name: f.name, family: file, category });
  });
  fs.writeFileSync(path.join(outSrc, file + '.json'), JSON.stringify({ full: src, fns: code, standalone: sa }));
  const css = path.join(dir, file + '.css');
  if (fs.existsSync(css)) fs.copyFileSync(css, path.join(outSrc, file + '.css'));
}
const header = '// This file is auto-generated by scripts/generate-catalog.js. Do not edit directly.\n';
const body = `export interface CatalogItem { id: string; name: string; family: string; category: string }\nexport const catalogItems: CatalogItem[] = ${JSON.stringify(items)};\n`;
fs.writeFileSync(path.join(__dirname, '../lib/catalog-index.ts'), header + body);
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.css'))) fs.copyFileSync(path.join(dir, f), path.join(outSrc, f));
console.log('catalog items:', items.length);
